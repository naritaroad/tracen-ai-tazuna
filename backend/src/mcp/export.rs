//! `tracen-api export-skills`: writes the outside agents' skill from the skills registry (§6.7):
//! `skills/tracen-public/SKILL.md` for any agent that reads Agent Skills, and the same text inside
//! the Claude Code plugin `plugins/tracen-academy`. Both are generated, never edited by hand; a test
//! checks they are current.

use std::path::Path;

use anyhow::{Context, Result};

use crate::skills::Registry;

pub const OUTPUT: &str = "skills/tracen-public/SKILL.md";
pub const PLUGIN_OUTPUT: &str = "plugins/tracen-academy/skills/tracen-public/SKILL.md";
pub const OUTPUTS: [&str; 2] = [OUTPUT, PLUGIN_OUTPUT];

pub fn render(registry: &Registry) -> String {
    let mut out = String::new();
    out.push_str("---\n");
    out.push_str("name: tracen-public\n");
    out.push_str(
        "description: \"Answer questions about Tracen Academy's public demo data (AI Hayakawa Tazuna, an unofficial fan project): \
         rules and procedures, the academy calendar and G1/G2 races, training facilities and training-plan totals, through the \
         tracen-academy-public MCP server. Also sends non-personal feedback about that data.\"\n",
    );
    out.push_str("compatibility: \"Needs the tracen-academy-public MCP server: `tracen-api mcp-stdio`, or Streamable HTTP at /mcp.\"\n");
    out.push_str("---\n\n");
    out.push_str("<!-- Generated by `tracen-api export-skills` from data/skills; do not edit by hand. -->\n\n");
    out.push_str("# Tracen Academy public data\n\n");
    out.push_str(
        "Everything this server returns is a demo setting of an unofficial doujin (fan) project (`source_type` project or reference) \
         or community game data (`source_type` community, with `source_ref`). It is never official Cygames material and never the \
         rules of a real school. Say so when you use it.\n\n",
    );
    out.push_str("## When to use it\n\n");
    out.push_str("- The user asks about Tracen Academy rules, procedures, dates, races, facilities or training-plan totals in this system.\n");
    out.push_str("- The user wants to report an error or missing information in this public data.\n\n");
    out.push_str("## When not to use it\n\n");
    out.push_str("- Private matters (a trainer's own conversations, cases, memories or account): this server cannot reach them.\n");
    out.push_str("- Anything that needs a person to decide (exceptions, complaints): the server cannot contact the Director's Office.\n\n");
    out.push_str("## Tools\n\n");
    for skill in registry.enabled().filter(|s| s.entry.surfaces.iter().any(|x| x == "mcp") && s.entry.visibility == "public") {
        out.push_str(&format!("### {}\n\n{}\n\n", skill.entry.name, skill.external));
    }
    out.push_str("## Rules\n\n");
    out.push_str("- Answer only from tool results. If a tool says `found: false`, say it was not found; do not guess.\n");
    out.push_str("- Never add up minutes or fees yourself; call `calculate_training_plan`.\n");
    out.push_str("- Cite handbook section numbers (for example §3.2) and the `source_type` of what you used.\n");
    out.push_str("- Do not speak for the academy, the Director or the Director's Office, and do not promise anything on their behalf.\n");
    out.push_str("- Feedback: one call per report, a new `idempotency_key` each time, and no personal data of anyone.\n");
    out
}

pub fn write(registry: &Registry, root: &Path) -> Result<Vec<std::path::PathBuf>> {
    let text = render(registry);
    let mut written = Vec::new();
    for output in OUTPUTS {
        let path = root.join(output);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).with_context(|| format!("create {}", dir.display()))?;
        }
        std::fs::write(&path, &text).with_context(|| format!("write {}", path.display()))?;
        written.push(path);
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_committed_files_are_current() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        for output in OUTPUTS {
            let committed = std::fs::read_to_string(root.join(output)).unwrap_or_default().replace("\r\n", "\n");
            assert_eq!(committed, render(crate::skills::registry()), "run `cargo run -- export-skills` and commit {output}");
        }
    }

    #[test]
    fn hand_over_is_not_offered_outside() {
        let text = render(crate::skills::registry());
        assert!(text.contains("search_public_rules") && text.contains("submit_public_feedback"));
        assert!(!text.contains("transfer_to_director"));
        assert!(text.starts_with("---\nname: tracen-public\n"));
    }
}
